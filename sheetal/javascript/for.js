// for loop
// 1 to 5
for (let i = 1; i <= 5; i++) {
  console.log(i);
}


//5 to 1
for( let a = 5; a >= 0; a--) {
  console.log(a);
}

// even numbers
for (b = 2; b <= 30; b+=2) {
  console.log(b);
}


// odd numbers
for (c = 1; c <= 30; c+=2) {
  console.log(c);
}

// sum of numbers
let sum = 0;

for (let d = 1; d <= 10; d++) {
    sum += d;
}

console.log("Sum =", sum);

